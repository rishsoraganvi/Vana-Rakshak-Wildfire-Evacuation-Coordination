import uuid
from datetime import UTC, datetime

import pytest
from pydantic import ValidationError
from wildfire_core.schemas.phase2 import (
    AuditEntry,
    CoordinatorPlan,
    FireSpreadResult,
    HotspotCluster,
    RouteResult,
    WeatherSnapshot,
)


def test_hotspot_cluster_uuid_autogenerated():
    c = HotspotCluster(
        centroid_lat=11.72,
        centroid_lon=76.64,
        point_count=5,
        mean_frp=15.2,
        bbox_west=76.60,
        bbox_south=11.70,
        bbox_east=76.68,
        bbox_north=11.74,
    )
    assert c.cluster_id is not None
    assert uuid.UUID(c.cluster_id)
    assert c.point_count == 5
    assert c.mean_frp == 15.2


def test_weather_snapshot_stale_fields():
    now = datetime.now(UTC)
    w_fresh = WeatherSnapshot(
        valid_time=now,
        wind_speed_ms=4.5,
        wind_dir_deg=90.0,
        rh_pct=40.0,
        temperature_c=32.0,
    )
    assert w_fresh.is_stale is False
    assert w_fresh.stale_age_min is None

    w_stale = WeatherSnapshot(
        valid_time=now,
        wind_speed_ms=4.5,
        wind_dir_deg=90.0,
        rh_pct=40.0,
        temperature_c=32.0,
        is_stale=True,
        stale_age_min=120,
    )
    assert w_stale.is_stale is True
    assert w_stale.stale_age_min == 120


def test_route_result_blocked_classification():
    r = RouteResult(
        group_id="group-1",
        origin_settlement_id="settlement-1",
        osm_node_path=(1001, 1002, 1003),
        total_distance_m=1500.0,
        estimated_travel_time_s=120.0,
        safety_classification="blocked",
        fire_penalty_edges=(1002,),
    )
    assert r.safety_classification == "blocked"
    assert len(r.osm_node_path) == 3
    assert uuid.UUID(r.route_id)

    cluster_route = RouteResult(
        group_id="group-1",
        origin_cluster_id="cluster-1",
        osm_node_path=(1001, 1002),
        total_distance_m=750.0,
        estimated_travel_time_s=60.0,
        safety_classification="safe",
    )
    assert cluster_route.origin_settlement_id is None
    assert cluster_route.origin_cluster_id == "cluster-1"

    with pytest.raises(ValidationError):
        RouteResult(
            group_id="group-1",
            origin_settlement_id="settlement-1",
            osm_node_path=(1001,),  # min_length=2 required
            total_distance_m=10.0,
            estimated_travel_time_s=1.0,
            safety_classification="safe",
        )

    route_fields = {
        "group_id": "group-1",
        "osm_node_path": (1001, 1002),
        "total_distance_m": 750.0,
        "estimated_travel_time_s": 60.0,
        "safety_classification": "safe",
    }
    with pytest.raises(ValidationError):
        RouteResult(**route_fields)
    with pytest.raises(ValidationError):
        RouteResult(
            **route_fields,
            origin_settlement_id="settlement-1",
            origin_cluster_id="cluster-1",
        )


