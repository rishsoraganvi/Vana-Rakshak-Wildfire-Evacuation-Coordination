def test_coordinator_plan_default_status_draft():
    now = datetime.now(UTC)
    weather = WeatherSnapshot(
        valid_time=now,
        wind_speed_ms=3.0,
        wind_dir_deg=180.0,
        rh_pct=45.0,
        temperature_c=28.0,
    )
    fire_result = FireSpreadResult(
        cluster_id=str(uuid.uuid4()),
        current_perimeter_wkt="POLYGON EMPTY",
        p50_1h_wkt="POLYGON EMPTY",
        p50_3h_wkt="POLYGON EMPTY",
        p50_6h_wkt="POLYGON EMPTY",
        p90_1h_wkt="POLYGON EMPTY",
        p90_3h_wkt="POLYGON EMPTY",
        p90_6h_wkt="POLYGON EMPTY",
        affected_area_km2=0.0,
        spread_direction_deg=180.0,
        spread_rate_m_per_h=0.0,
        confidence="medium",
    )
    plan = CoordinatorPlan(
        incident_id=str(uuid.uuid4()),
        run_id=str(uuid.uuid4()),
        fire_result=fire_result,
        weather_snapshot=weather,
        clusters=(),
        routes=(),
        rationale_md="Test rationale",
    )
    assert plan.status == "draft"
    assert plan.is_llm_fallback is False
    assert plan.rationale_md == "Test rationale"
    assert uuid.UUID(plan.plan_id)
